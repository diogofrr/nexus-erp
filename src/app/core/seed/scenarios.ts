  city?: string;
  /** Horas diárias de cuidado (5.7). */
  hours: number;
  channel: Channel;
  literacy: 'low' | 'medium' | 'high';
  dependency: Dependency;
  pilot: boolean;
  /** Frase do cenário-chave (para a documentação e para o QA). */
